-- =====================================================================
--  LÅTSNURRAN 0085 – kategorin "Solo eller grupp"
--
--  Hjulets svagaste fråga var "Svenskt eller inte": svaret hörs i låten,
--  och med två alternativ träffar även den som inte kan låten rätt
--  varannan gång. Den ersätts i väljaren av en fråga som kräver att man
--  vet något om artisten – är det en soloartist eller en grupp?
--
--  DATAN ÄR NY OCH KONTROLLERAD I TRE LED (scripts/*-artist-types.mjs):
--   1. Artisttypen slogs upp i MusicBrainz för 4 025 krediteringar. Bara
--      EXAKTA namnträffar räknas – därför faller samarbeten bort av sig
--      själva: ingen artist heter "Kygo, Khalid & Gryffin", medan
--      "Simon & Garfunkel" är en enda grupp och matchar.
--   2. Namnkrockar ("Shakira" är både colombianskan och en tysk grupp)
--      avgjordes genom att fråga MusicBrainz vem som SPELADE IN låten –
--      200 av 235 gick att reda ut så. Resten lämnas okända.
--   3. Allt stämdes av mot Wikidata, som har egen uppgift om samma
--      artister via MusicBrainz-id. Källorna var oense om 0,41 %
--      (15 av 3 615), och avvikarna var inte slumpfel utan en samman-
--      hängande grupp: enmansprojekt som uppträder som band (Tame Impala,
--      Owl City, City and Colour, Hello Saferide, White Town). Alla 15
--      är uteslutna.
--
--  Resultat: 9 330 av 10 226 låtar (91,2 %) har en typ, fördelat 56 %
--  solo / 44 % grupp – jämnt nog att gissa aldrig lönar sig.
--
--  DÄRFÖR HAR INTE ALLA LÅTAR EN TYP, och det är avsiktligt: samarbeten,
--  olösta namnkrockar och artister utan typuppgift lämnas tomma. En låt
--  utan artisttyp dyker aldrig upp i en solo/grupp-runda. Det kostar
--  täckning, aldrig ett felaktigt svar – samma linje som genre (0084),
--  där låtar utan genre hålls utanför genre-rundor. Sämsta urvalet med
--  minst 25 låtar (svensk hiphop 2025–2029) har 24 låtar med typ, så
--  ingen realistisk pott kan bli stående utan låt.
--
--  'swedish' ÄR KVAR SOM GILTIGT VÄRDE här, trots att väljaren slutar
--  erbjuda den. Rum som redan valt den ska kunna spela klart, och
--  rounds-tabellens historik innehåller rundor med den kategorin –
--  en check-constraint som förbjöd värdet hade avvisat gamla rader.
--
--  REGELN FRÅN 0037 GÄLLER: en ny kategori kräver ändring på TRE ställen
--  – _room_categories (via _valid_categories), rounds_category_check och
--  _judge_answer. Alla tre finns nedan.
--
--  Funktionskropparna är LIVE-DUMPAR med kirurgiska byten (metoden från
--  0027/0084) så att inga senare tillägg tappas bort på vägen. Varje byte
--  räknas vid genereringen – uteblivet byte stoppar den.
--
--  Additiv + idempotent. Kör efter 0084.
-- =====================================================================

