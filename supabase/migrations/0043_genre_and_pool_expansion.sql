-- =====================================================================
--  0043  Genre på låtarna + utökad låtpott
-- ---------------------------------------------------------------------
--  TVÅ SAKER I EN MIGRATION eftersom de hänger ihop: genrelägen är
--  meningslösa utan tillräckligt med låtar per genre, och de nya låtarna
--  är insamlade med genre från början.
--
--  1. track_pool.genre – Deezers rågenre ("Rap/Hip Hop", "Alternativmusik").
--     Den lagras ORÖRD; mappningen till spelbara lägen görs av _genre_key()
--     så att indelningen kan ändras utan att datan hämtas om.
--
--  2. 2317 nya låtar som INTE finns på Hitster-korten. Insamlade från
--     Deezers topplistor + relaterade artister, och årsverifierade mot TVÅ
--     oberoende källor (Deezer + MusicBrainz måste ge samma år, annars
--     slängdes låten). Bara 1990+: äldre material daterar båda källorna till
--     ÅTERUTGIVNINGEN, inte originalet – uppmätt exakthet mot Hitster-kortens
--     kända år var 5 % på 60–80-talet mot 82–91 % på 2010/2020-talet.
--
--  3. rooms.genre + filter i start_random_track.
--
--  OBS sv-partitioneringen: alla nya låtar går in med sv = false. 71 låtar
--  ligger medvetet i BÅDA potterna (0039) och den balansen rörs inte här.
--
--  Idempotent. Kör efter 0042.
-- =====================================================================

-- ---------------------------------------------------------------------
--  1. Genrekolumn + mappning till spelbara lägen
-- ---------------------------------------------------------------------
alter table public.track_pool add column if not exists genre text;

-- Deezers etiketter är grova och delvis svenska. Mappningen slår ihop det
-- som folk ändå uppfattar som samma sak: "Alternativmusik" och "Metal" är
-- rock för ett sällskap som spelar musikquiz, "Electro"/"Disco" är dans.
-- Låtar utan mappning finns kvar i "Alla låtar" men i inget genreläge.
create or replace function public._genre_key(p_genre text)
returns text
language sql
immutable
as $$
  select case
    when p_genre is null then null
    when p_genre = 'Pop' then 'pop'
    when p_genre in ('Rock', 'Alternativmusik', 'Metal') then 'rock'
    when p_genre = 'Rap/Hip Hop' then 'hiphop'
    when p_genre in ('Dance', 'Electro', 'Disco') then 'dance'
    when p_genre in ('R&B', 'Soul & Funk') then 'rnb'
    else null
  end
$$;

create index if not exists track_pool_genre_idx
  on public.track_pool (sv, public._genre_key(genre));

